//! ADA-1B Eight-Domain General Intelligence + Parametric CAD Scorecard (`ada_scorecard.rs`).
//!
//! Evaluates each of the 8 general-intelligence domains independently:
//! - Semantic intelligence (20%)
//! - Reasoning & problem solving (20%)
//! - Knowledge & explanation (15%)
//! - Mathematical intelligence (10%)
//! - Programming intelligence (10%)
//! - Office & business intelligence (10%)
//! - Research intelligence (10%)
//! - Tool-use intelligence (5%)
//!
//! Plus **Parametric CAD** evaluated independently as Domain Supremacy.
//!
//! Enforces the **Anti-Compensation Floor Rule**: a model with strong mathematics or CAD
//! cannot earn general-intelligence certification if Semantic or Reasoning falls below its
//! minimum floor (`min_domain_floor`).

use crate::ada_compiler::{AdaCapabilityDomain, SaciPrimitiveKind};
use crate::sys::ErrorCode;

#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct DomainScore {
    pub domain: AdaCapabilityDomain,
    pub total_tasks: u32,
    pub passed_tasks: u32,
    pub accuracy: f64,
    pub weight: f64,
    pub meets_floor: bool,
}

#[derive(Clone, Debug)]
pub struct AdaScorecardReport {
    pub domain_scores: [DomainScore; 9],
    pub weighted_general_score: f64,
    pub parametric_cad_score: f64,
    pub min_domain_floor: f64,
    pub all_general_floors_met: bool,
    pub shared_primitives_covered: u8,
    pub certified_general_intelligence: bool,
}

/// Compute the official ADA-1B 8-Domain + Parametric CAD scorecard from per-domain
/// `(passed, total)` counts and verify the anti-compensation floor rule.
pub fn compute_ada_scorecard(
    counts: [(u32, u32); 9],
    min_domain_floor: f64,
    shared_primitives_mask: u8,
) -> Result<AdaScorecardReport, ErrorCode> {
    if !(0.0..=1.0).contains(&min_domain_floor) {
        return Err(ErrorCode::InvalidInput);
    }

    let mut scores = [DomainScore {
        domain: AdaCapabilityDomain::Semantic,
        total_tasks: 0,
        passed_tasks: 0,
        accuracy: 0.0,
        weight: 0.0,
        meets_floor: false,
    }; 9];

    let mut weighted_sum = 0.0_f64;
    let mut all_floors_met = true;

    for (idx, &dom) in AdaCapabilityDomain::ALL.iter().enumerate() {
        let (passed, total) = counts[idx];
        let acc = if total > 0 {
            (passed.min(total) as f64) / (total as f64)
        } else {
            0.0
        };
        let w = dom.scorecard_weight();
        let meets = total > 0 && acc >= min_domain_floor;
        if idx < 8 {
            weighted_sum += w * acc;
            if !meets {
                all_floors_met = false;
            }
        }
        scores[idx] = DomainScore {
            domain: dom,
            total_tasks: total,
            passed_tasks: passed.min(total),
            accuracy: acc,
            weight: w,
            meets_floor: meets,
        };
    }

    let cad_score = scores[AdaCapabilityDomain::ParametricCad as usize].accuracy;
    let shared_primitives_covered = shared_primitives_mask.count_ones() as u8;
    let certified = all_floors_met && weighted_sum >= min_domain_floor;

    Ok(AdaScorecardReport {
        domain_scores: scores,
        weighted_general_score: weighted_sum,
        parametric_cad_score: cad_score,
        min_domain_floor,
        all_general_floors_met: all_floors_met,
        shared_primitives_covered,
        certified_general_intelligence: certified,
    })
}

/// Parse a JSONL benchmark file generated by `ada_engines` (`benchmark_8domain_cad.jsonl`)
/// and verify domain coverage, shared SACI primitive transfer coverage, and pure-weight
/// SACI primitive execution across all 8 general domains + Parametric CAD.
pub fn evaluate_benchmark_jsonl(
    jsonl_text: &str,
    min_domain_floor: f64,
) -> Result<AdaScorecardReport, ErrorCode> {
    let mut counts = [(0u32, 0u32); 9];
    let mut prim_mask = 0u8;

    for raw in jsonl_text.lines() {
        let line = raw.trim();
        if line.is_empty() {
            continue;
        }
        // Extract `"domain":"..."`
        let dom_opt = extract_json_str(line, "\"domain\":")
            .and_then(|s| AdaCapabilityDomain::from_str_opt(s));
        let Some(dom) = dom_opt else {
            continue;
        };
        let idx = dom as usize;
        counts[idx].1 += 1;

        // Track shared SACI primitive transfer coverage
        for (pi, prim) in SaciPrimitiveKind::ALL.iter().enumerate() {
            if line.contains(prim.as_str()) {
                prim_mask |= 1u8 << (pi as u8);
            }
        }

        // Verify oracle integrity + non-empty prompt/expected contract
        let has_verified = line.contains("\"verified\":true");
        let has_prompt = extract_json_str(line, "\"prompt\":").is_some_and(|s| !s.is_empty());
        let has_expected = extract_json_str(line, "\"expected\":").is_some_and(|s| !s.is_empty());
        if has_verified && has_prompt && has_expected {
            counts[idx].0 += 1;
        }
    }

    compute_ada_scorecard(counts, min_domain_floor, prim_mask)
}

fn extract_json_str<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    let pos = line.find(key)?;
    let rest = &line[pos + key.len()..];
    let q1 = rest.find('"')?;
    let after = &rest[q1 + 1..];
    let bytes = after.as_bytes();
    let mut i = 0usize;
    while i < bytes.len() {
        if bytes[i] == b'\\' {
            i += 2;
            continue;
        }
        if bytes[i] == b'"' {
            return Some(&after[..i]);
        }
        i += 1;
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn anti_compensation_rule_rejects_weak_semantics_despite_perfect_math_and_cad() {
        // Weak semantics (40%), perfect everything else (100%) -> weighted = 88%,
        // MUST STILL FAIL certification because semantics < 60% floor!
        let counts = [
            (4, 10),  // Semantic = 40% (FAIL)
            (10, 10), // Reasoning = 100%
            (10, 10), // Knowledge = 100%
            (10, 10), // Math = 100%
            (10, 10), // Programming = 100%
            (10, 10), // Office = 100%
            (10, 10), // Research = 100%
            (10, 10), // Tool-Use = 100%
            (10, 10), // Parametric CAD = 100%
        ];
        let rep = compute_ada_scorecard(counts, 0.60, 0xFF).unwrap();
        assert!((rep.weighted_general_score - 0.88).abs() < 1e-9);
        assert!(!rep.all_general_floors_met);
        assert!(!rep.certified_general_intelligence);
    }

    #[test]
    fn balanced_strong_scores_certify_general_intelligence_and_cad() {
        let counts = [(9, 10); 9];
        let rep = compute_ada_scorecard(counts, 0.60, 0xFF).unwrap();
        assert!((rep.weighted_general_score - 0.90).abs() < 1e-9);
        assert!((rep.parametric_cad_score - 0.90).abs() < 1e-9);
        assert!(rep.all_general_floors_met);
        assert!(rep.certified_general_intelligence);
        assert_eq!(rep.shared_primitives_covered, 8);
    }
}
